#!/usr/bin/env python3
"""chscan_gen.py — turn chscan manifest lines into mirakc config files.

Input (stdin file): TSV lines "TYPE<TAB>CHANNEL<TAB>JSON"
Output:
  config/config.yml     (channels: block replaced, rest preserved)
  config/channels.yml   (generated channels block, sample/reference)
  config/services.json  (mirakc EPG service cache)
"""

import json
import os
import sys

TYPE_ORDER = {"GR": 0, "BS": 1, "CS": 2, "BS4K": 3, "CATV": 4}


def channel_sort_key(entry):
    t = entry["type"]
    ch = entry["channel"]
    order = TYPE_ORDER.get(t, 9)
    if t == "GR" or t == "CS" or t == "BS4K":
        try:
            return (order, int(ch), "")
        except ValueError:
            return (order, 0, ch)
    if t == "BS":
        # BSxx_y -> (xx, y)
        try:
            body = ch[2:]
            tp, y = body.split("_")
            return (order, int(tp), int(y))
        except Exception:
            return (order, 0, ch)
    if t == "CATV":
        try:
            return (order, int(ch[1:]), ch[0])
        except Exception:
            return (order, 0, ch)
    return (order, 0, ch)


def load_manifest(path):
    entries = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            parts = line.split("\t", 2)
            if len(parts) != 3:
                continue
            typ, ch, raw = parts
            try:
                services = json.loads(raw)
            except Exception:
                continue
            if not isinstance(services, list) or not services:
                continue
            sids = []
            for s in services:
                sid = s.get("sid")
                if isinstance(sid, int) and sid not in sids:
                    sids.append(sid)
            if not sids:
                continue
            name = services[0].get("name") or ch
            entries.append({
                "type": typ,
                "channel": ch,
                "name": name,
                "services": services,
                "sids": sids,
            })
    entries.sort(key=channel_sort_key)
    return entries


def yaml_block(entries):
    lines = ["channels:", "  # generated by make chscan"]
    for e in entries:
        lines.append("  - name: %s" % json.dumps(e["name"], ensure_ascii=False))
        lines.append("    type: %s" % e["type"])
        lines.append("    channel: %s" % json.dumps(e["channel"], ensure_ascii=False))
        lines.append("    services: [%s]" % ", ".join(str(x) for x in e["sids"]))
    return lines


def patch_config(entries, path):
    block = yaml_block(entries) + [""]
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()

    start = None
    for i, line in enumerate(lines):
        if line.rstrip() == "channels:":
            start = i
            break
    if start is None:
        # Insert before tuners: (or at the end)
        for i, line in enumerate(lines):
            if line.rstrip() == "tuners:":
                lines[i:i] = block
                break
        else:
            lines.extend(block)
    else:
        end = len(lines)
        for i in range(start + 1, len(lines)):
            line = lines[i]
            if not line or line.startswith((" ", "\t", "#")):
                continue
            if line.rstrip().endswith(":"):
                end = i
                break
        lines[start:end] = block

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_channels_yml(entries, path):
    header = [
        "# generated by make chscan",
        "# このファイルは参照用です。mirakc は config/config.yml の channels を読みます。",
        "",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(header + yaml_block(entries)) + "\n")


def write_services_json(entries, path):
    by_id = {}
    for e in entries:
        ch_name = e["name"]
        ch_type = e["type"]
        ch_channel = e["channel"]
        sids = e["sids"]
        ch_obj = {
            "name": ch_name,
            "type": ch_type,
            "channel": ch_channel,
            "extra_args": "",
            "services": sids,
            "excluded_services": [],
        }
        for s in e["services"]:
            sid = s.get("sid")
            nid = s.get("nid")
            if not isinstance(sid, int) or not isinstance(nid, int):
                continue
            sid_value = nid * 100000 + sid
            svc = {
                "id": sid_value,
                "type": s.get("type", 1),
                "logoId": s.get("logoId", -1),
                "remoteControlKeyId": s.get("remoteControlKeyId", 0),
                "name": s.get("name", ch_name),
                "channel": ch_obj,
            }
            by_id[sid_value] = svc
    pairs = [[k, by_id[k]] for k in sorted(by_id)]
    with open(path, "w", encoding="utf-8") as f:
        json.dump(pairs, f, ensure_ascii=False, separators=(",", ":"))


def main():
    if len(sys.argv) != 3:
        print("usage: chscan_gen.py <manifest.tsv> <config-dir>", file=sys.stderr)
        return 2
    manifest, config_dir = sys.argv[1], sys.argv[2]
    entries = load_manifest(manifest)
    if not entries:
        print("chscan_gen: no scanned channels", file=sys.stderr)
        return 1

    patch_config(entries, os.path.join(config_dir, "config.yml"))
    write_channels_yml(entries, os.path.join(config_dir, "channels.yml"))
    write_services_json(entries, os.path.join(config_dir, "services.json"))

    counts = {}
    for e in entries:
        counts[e["type"]] = counts.get(e["type"], 0) + 1
    print("generated channels: " + ", ".join(
        "%s=%d" % (t, counts.get(t, 0)) for t in TYPE_ORDER if counts.get(t)
    ))
    return 0


if __name__ == "__main__":
    sys.exit(main())
